import { FACTS } from '@/lib/facts';
import { typo } from '@/lib/format';

/**
 * Перебивка между первым экраном и расчётом: три факта о поставке бегущей
 * строкой во всю ширину.
 *
 * Как это устроено. В ленте лежат одинаковые копии фактов, и вся лента едет
 * влево ровно на ширину ОДНОЙ копии — в этот момент вторая копия стоит там,
 * где начинала первая, и цикл повторяется без стыка. Двигается только
 * transform, ни background-position, ни margin: строка идёт на композиторе и
 * не трогает вёрстку.
 *
 * КОПИЙ ТРИ, А НЕ ДВЕ, И ЭТО НЕ ЗАПАС НА ВСЯКИЙ СЛУЧАЙ. Лента едет от 0 до
 * −ширина копии, то есть в самом конце цикла содержимое кончается на
 * отметке «ширина копии» от левого края. Пока копии было две, а экран шире
 * копии, правый край к концу цикла оголялся: на 1920 копия 1334,6 px, и за
 * 60 px до стыка справа оставалось 525 px пустоты, на 2560 — 1165. Дефект
 * был виден глазом и держался с самого появления ленты.
 *
 * Условие простое: копий должно хватить, чтобы закрыть экран в момент
 * стыка, то есть (копий − 1) × ширина копии ≥ ширина экрана. При копии
 * 1334,6 px три копии закрывают 2669 px — больше самого широкого
 * проверяемого экрана 2560.
 *
 * Копии со второй — технические: помечены aria-hidden и показываются только
 * при классе `js` на <html>. Без скрипта и в режиме покоя остаётся один ряд
 * из трёх фактов, стоящий на месте, — ровно то, что было до бегущей строки.
 *
 * Скорость и торможение при наведении — в Motion.tsx: там лента получает
 * бесконечный tween, а наведение сбавляет ему timeScale до четверти. Менять
 * длительность CSS-анимации на лету нельзя — она перескакивает.
 *
 * Факты разделяет промежуток, а не знак. Точки между ними больше нет: она
 * стояла ВНУТРИ факта, последней, и у последнего факта висела в пустоте —
 * в режиме покоя, где копия одна, ряд кончался точкой, за которой ничего.
 * Ширину точка занимала небольшую, а работу делала промежутком вокруг себя;
 * теперь этот промежуток отдан целиком пробелу, см. .marquee-item в
 * globals.css.
 */
export function FactsStrip() {
  const copy = (n: number) => (
    <div
      key={n}
      className="marquee-copy"
      data-marquee-clone={n > 0 ? '' : undefined}
      aria-hidden={n > 0 ? 'true' : undefined}
    >
      {FACTS.map((f) => (
        <div key={f.label} className="marquee-item">
          <span className="text-t1 text-ink-2">{f.label}</span>
          <span className="text-t2 font-medium leading-snug">{typo(f.value)}</span>
        </div>
      ))}
    </div>
  );

  return (
    /* Полоса наезжает на первый экран верхним краем со скруглением: секции
       не встают встык, а перетекают. Отрицательный отступ съедает нижнюю
       кромку кадра, скругление отделяет полосу от фотографии. */
    <div className="inv marquee-strip relative z-10 -mt-10 rounded-t-panel md:-mt-14" data-marquee>
      <div className="marquee-track" data-marquee-track>
        {copy(0)}
        {copy(1)}
        {copy(2)}
      </div>
    </div>
  );
}
