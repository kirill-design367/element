import { ART, PATHS, type Art } from '@/lib/logo-art';

/**
 * ЗНАК В РАЗМЕТКЕ САЙТА.
 *
 * Контуры берутся из того же `ART`, что и на визитке, и собраны тем же
 * скриптом из шрифта — здесь ничего не рисуется заново. Отличается только
 * способ вывода: визитка строит HTML строкой, сайту нужен React-узел.
 *
 * БЕРЁТСЯ ВЕРСИЯ БЕЗ ПЛАШКИ (`o1-n`), а не та, что на визитке (`o1`). Причина
 * не в экономии: у версии с плашкой ДВЕ роли краски — сама плашка и то, что
 * из неё вынуто, — и одним `currentColor` их не покрасить. А в шапке цвет
 * обязан наследоваться от темы: панель висит и над фотографией, и над
 * светлыми секциями. У версии без плашки обе части одной роли, поэтому весь
 * знак — один `currentColor`, и он ведёт себя как текст, который заменил.
 *
 * Композиция та же самая: та же скоба, то же слово, те же буквы. Снята
 * только подложка — ровно для этого версия без плашки и существует.
 *
 * ВЫСОТА ЗАДАЁТСЯ СНАРУЖИ, ширина считается из пропорции коробки. Держать
 * наоборот нельзя: у знака отношение сторон 5:1, и заданная ширина на узком
 * экране уронила бы высоту до нечитаемой.
 */
export function Logo({
  id = 'o1-n',
  className = '',
}: {
  /** Ключ композиции в ART. По умолчанию выбранная вариация без плашки. */
  id?: string;
  className?: string;
}) {
  const art: Art | undefined = ART[id];
  if (!art) return null;
  return (
    <svg
      viewBox={`0 0 ${art.w} ${art.h}`}
      className={className}
      /* Знак — картинка, а не текст: доступное имя даёт соседний sr-only
         span, чтобы оно совпадало с тем, что читает человек. */
      aria-hidden="true"
      focusable="false"
    >
      {art.parts.map((part, i) =>
        part.d ? (
          <path key={i} d={part.d} fill="currentColor" />
        ) : (
          <path
            key={i}
            d={PATHS[part.ref as string]}
            transform={`translate(${part.x ?? 0} ${part.y ?? 0})`}
            fill="currentColor"
          />
        ),
      )}
    </svg>
  );
}
