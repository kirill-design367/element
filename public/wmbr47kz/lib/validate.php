/**
 * ПРОВЕРКА ПОЛЕЙ НА СЕРВЕРЕ.
 *
 * Браузерная проверка это удобство, а не защита: до любой страницы админки
 * можно достучаться curl'ом, минуя форму. Всё, что приходит из формы,
 * проверяется здесь — типы, длины, диапазоны, — и ошибки объясняются
 * словами, а не кодом.
 *
 * ОТДЕЛЬНО ПРО ПУСТОТУ И НОЛЬ. Цена может отсутствовать, и это НЕ ноль:
 * пустое поле означает «цены в прайсе нет» и на сайте превращается в
 * «уточняйте у менеджера», а ноль означал бы «бесплатно». Поэтому у цены
 * своя функция, которая возвращает null для пустой строки и число для
 * заполненной, включая ноль.
 */

/** Обрезка управляющих символов и лишних пробелов по краям. */
function clean(string $name, int $limit = 500): string
{
    $raw = (string) ($_POST[$name] ?? '');
    $s = preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]+/u', '', $raw) ?? '';
    /* Перевод строки оставляем только там, где он осмыслен (uses, summary):
       за это отвечает вызывающий, передавая многострочный текст через
       clean_multi(). Здесь строка сводится к одной.

       НЕРАЗРЫВНЫЕ ПРОБЕЛЫ НЕ ТРОГАЕМ. С флагом /u `\s` ловит и U+00A0, и
       до 13.10 каждое сохранение позиции проката молча меняло «⌀ 10 мм» с
       неразрывными пробелами на обычные — «мм» отрывалось от числа на узкой
       карточке. Схлопываются только обычные пробельные знаки. */
    $s = preg_replace('/[^\S\x{00A0}\x{202F}]+/u', ' ', $s) ?? '';
    /* А ПО КРАЯМ СРЕЗАЕТСЯ ЛЮБОЙ ПРОБЕЛ, неразрывный тоже: trim() знает только
       ASCII. Вставленный из PDF или Word ИНН с неразрывным пробелом на конце
       иначе не прошёл бы проверку «только цифры», а поле из одних
       неразрывных пробелов сошло бы за заполненное. */
    $s = preg_replace('/^\s+|\s+$/u', '', $s) ?? '';
    return mb_substr($s, 0, $limit, 'UTF-8');
}

/** То же, но переводы строк сохраняются: применения, описания. */
function clean_multi(string $name, int $limit = 4000): string
{
    $raw = (string) ($_POST[$name] ?? '');
    $s = preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]+/u', '', $raw) ?? '';
    $s = str_replace("\r\n", "\n", $s);
    return mb_substr(trim($s), 0, $limit, 'UTF-8');
}

/**
 * АДРЕС ЗАПИСИ ИЗ РУССКОГО ТЕКСТА: латиница, цифры и дефис.
 *
 * Адрес — внутренний ключ позиции: по нему сайт связывает заявку, расчёт и
 * карточку. Придумывать его человеку незачем, и до 13.10 это было хуже, чем
 * незачем: форма новой позиции требовала адрес, но поля для него не имела
 * вовсе, и НИ ОДНА новая позиция не сохранялась — с ошибкой «посмотрите
 * поля, отмеченные красным» при ни одном красном поле. Теперь адрес
 * выводится из названия, разновидности и размера: «Щебень гранитный 5–20» →
 * `shcheben-granitnyy-5-20`.
 */
function slug_ru(string $text, int $limit = 56): string
{
    $map = [
        'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'е' => 'e', 'ё' => 'e',
        'ж' => 'zh', 'з' => 'z', 'и' => 'i', 'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm',
        'н' => 'n', 'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't', 'у' => 'u',
        'ф' => 'f', 'х' => 'h', 'ц' => 'ts', 'ч' => 'ch', 'ш' => 'sh', 'щ' => 'shch', 'ъ' => '',
        'ы' => 'y', 'ь' => '', 'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
    ];
    $s = strtr(mb_strtolower($text, 'UTF-8'), $map);
    $s = trim(preg_replace('/[^a-z0-9]+/', '-', $s) ?? '', '-');
    /* Обрезка по дефису, а не посреди слова, и без висящего дефиса на конце. */
    if (strlen($s) > $limit) {
        $s = substr($s, 0, $limit);
        $cut = strrpos($s, '-');
        $s = $cut !== false && $cut > $limit / 2 ? substr($s, 0, $cut) : rtrim($s, '-');
    }
    return $s;
}

/**
 * НЕРАЗРЫВНЫЕ ПРОБЕЛЫ В ОБОЗНАЧЕНИИ ПАРТИИ — как у всех позиций на сайте:
 * после «⌀» и «№» и перед единицей на конце. Подпись выводится на сайте как
 * есть, без типографского хелпера, и обычный пробел отпустил бы «мм» на
 * следующую строку карточки.
 */
function nbsp_units(string $s): string
{
    $s = preg_replace('/(?<=[⌀№]) (?=\S)/u', "\u{00A0}", $s) ?? $s;
    return preg_replace('/(?<=\S) (?=(?:мм|см|м|%)$)/u', "\u{00A0}", $s) ?? $s;
}

/** Число для подписи: 1.80 → «1,8», 5.00 → «5». */
function dec_label(float $x): string
{
    return rtrim(rtrim(number_format($x, 2, ',', ''), '0'), ',');
}

/**
 * ЧИСЛО ИЛИ ПУСТО. Возвращает null, если поле не заполнено, и false, если
 * заполнено мусором: три исхода, а не два, потому что «пусто» и «ерунда» —
 * разные вещи, и отвечать на них надо по-разному.
 *
 * Запятая понимается как десятичный разделитель: на русской раскладке её и
 * набирают. Пробелы выбрасываются — сайт сам печатает числа разрядкой.
 */
function num_or_null(string $name): float|null|false
{
    $raw = trim((string) ($_POST[$name] ?? ''));
    if ($raw === '') {
        return null;
    }
    $bare = str_replace([' ', "\u{00A0}", "\u{202F}", ','], ['', '', '', '.'], $raw);
    if (!is_numeric($bare)) {
        return false;
    }
    return (float) $bare;
}

/** Значение из закрытого списка. Чужое — первое из списка. */
function one_of(string $name, array $allowed, string $fallback): string
{
    $v = (string) ($_POST[$name] ?? '');
    return in_array($v, $allowed, true) ? $v : $fallback;
}

function checkbox(string $name): bool
{
    return isset($_POST[$name]) && $_POST[$name] !== '';
}
