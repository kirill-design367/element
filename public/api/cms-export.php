 * ЗАКРЫТО КЛЮЧОМ, И ЭТО НЕ ПЕРЕСТРАХОВКА. Снимок отдаётся ЦЕЛИКОМ — это
 * готовая выгрузка базы, — и отдавать её анониму незачем, даже если каждое
 * поле по отдельности где-то на сайте видно. Здесь стояло «банковские
 * реквизиты на сайте не показываются нигде» — это было неверно всегда:
 * блок «Реквизиты» на главной их выводит.
 *
 * Ключ живёт в файле настроек на хостинге и в секретах репозитория под
 * именем CMS_EXPORT_KEY. Сравнение через hash_equals: обычное сравнение
 * строк выходит из цикла на первом несовпавшем символе, и ключ подбирается
 * по времени ответа.
 *
 * ОТВЕТ ВСЕГДА JSON, даже на отказ: сборка печатает текст отказа в журнал.
 * Любой ответ, кроме 200, ОСТАНАВЛИВАЕТ сборку (scripts/cms-fetch.mjs), и
 * данные из репозитория берутся только тогда, когда человек сам поставил
 * галочку при ручном запуске. Тихого отката на них нет с 30.08.
 */

header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store');
header('X-Robots-Tag: noindex, nofollow');

/* Библиотеки панели берутся из её папки. Папка переехала 07.10 с admin/ на
   wmbr47kz/ — антибот хостинга режет адреса со словом «admin», — и путь
   здесь обязан переезжать вместе с ней: иначе выгрузка падает 500, сборка
   не получает снимок, и публикация из панели перестаёт доезжать до сайта. */
require_once __DIR__ . '/../wmbr47kz/lib/config-load.php';
require_once __DIR__ . '/../wmbr47kz/lib/db.php';

function out(int $code, array $body): never
{
    http_response_code($code);
    echo json_encode($body, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

$config = cms_config();
$expected = (string) ($config['export_key'] ?? '');
if ($expected === '') {
    out(500, ['ok' => false, 'error' => 'На хостинге не задан export_key.']);
}

/* Ключ принимается заголовком, а не в адресе: адреса попадают в логи
   сервера и в историю, заголовки — нет. */
$given = (string) ($_SERVER['HTTP_X_CMS_KEY'] ?? '');
if (!hash_equals($expected, $given)) {
    out(403, ['ok' => false, 'error' => 'Ключ не подошёл.']);
}

$row = q1('SELECT payload, digest, created_at FROM snapshots ORDER BY id DESC LIMIT 1');
if ($row === null) {
    /* Публикаций ещё не было. Сборка на этом остановится и скажет нажать
       «Опубликовать»; данные из репозитория — только галочкой при ручном
       запуске. */
    out(404, ['ok' => false, 'error' => 'Публикаций ещё не было.']);
}

$data = json_decode((string) $row['payload'], true);
if (!is_array($data)) {
    out(500, ['ok' => false, 'error' => 'Снимок в базе повреждён.']);
}

out(200, [
    'ok' => true,
    'digest' => (string) $row['digest'],
    'published' => (string) $row['created_at'],
    'data' => $data,
]);
