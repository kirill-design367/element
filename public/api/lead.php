<?php
declare(strict_types=1);

/**
 * ПРИЁМНИК ЗАЯВКИ С САЙТА.
 *
 * Сайт статический: страницы собраны заранее и лежат файлами. Единственное
 * место, где на сервере выполняется наш код, — этот скрипт. Он делает ровно
 * одно: принимает поля формы и отправляет письмо на адрес заказчика. Ни
 * базы, ни хранения, ни очереди — заявка живёт только в письме.
 *
 * АДРЕС ЗДЕСЬ НЕ НАБРАН. Он приходит из `config.php`, который собирается при
 * сборке из `lib/company.ts` — там же, где остальные контакты сайта.
 *
 * ОТВЕЧАЕТ ВСЕГДА JSON. Форма разбирает ответ и по нему решает, показать
 * подтверждение или ошибку с телефоном.
 *
 *   200 {"ok":true}                     — письмо ушло
 *   405 {"ok":false,"error":"…"}        — не POST
 *   422 {"ok":false,"errors":{…}}       — поля не прошли проверку
 *   429 {"ok":false,"error":"…"}        — слишком часто с одного адреса
 *   500 {"ok":false,"error":"…"}        — нет настроек
 *   502 {"ok":false,"error":"…"}        — почтовая подсистема отказала
 *
 * ЗАЩИТА ОТ СПАМА — ЧЕТЫРЕ МЕХАНИЗМА И НИ ОДНОЙ КАПЧИ. Капча стоит заявок:
 * снабженец с телефона, не разобравший картинку, просто уходит. Вместо неё
 * ловушка, часы, ограничение частоты и разбор полей — всё на сервере.
 *
 * ЛОВУШКА И ЧАСЫ ОТВЕЧАЮТ УСПЕХОМ И НИЧЕГО НЕ ШЛЮТ. Это не небрежность:
 * бот, получивший отказ, подбирает обход, а получивший «ок» — уходит
 * довольным. Человек в эти две ветки не попадает: поле ловушки не видно и
 * не получает фокуса, а часы отмеряют время с загрузки формы, которого у
 * человека уходит десятки секунд.
 */

header('Content-Type: application/json; charset=utf-8');
/* Ответ индивидуален и кешироваться не должен ни на секунду. */
header('Cache-Control: no-store');
/* Скрипт вызывается только своей же страницей: заголовок CORS не выдаётся
   намеренно, чужой сайт нашу форму не переиспользует. */

/** Ответ и выход. Одной дверью, чтобы формат не разошёлся по веткам. */
function reply(int $code, array $body): never
{
    http_response_code($code);
    echo json_encode($body, JSON_UNESCAPED_UNICODE);
    exit;
}

if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
    /* Allow обязателен по стандарту и полезен на деле: по нему сразу видно,
       что скрипт исполняется, а не отдан текстом. */
    header('Allow: POST');
    reply(405, ['ok' => false, 'error' => 'Метод не поддерживается: нужен POST.']);
}

$configPath = __DIR__ . '/config.php';
if (!is_file($configPath)) {
    reply(500, ['ok' => false, 'error' => 'Приём заявок не настроен на сервере.']);
}
$config = require $configPath;
if (!is_array($config) || empty($config['to']) || empty($config['from'])) {
    reply(500, ['ok' => false, 'error' => 'Приём заявок не настроен на сервере.']);
}

/* ─── ЧАСТОТА ────────────────────────────────────────────────────────────
 *
 * Три письма за десять минут и двенадцать за сутки с одного адреса. Больше
 * — отвечаем 429 ЧЕСТНО, а не молчанием: в этот предел упирается человек,
 * а не бот, и он должен понять, что произошло, и позвонить.
 *
 * ЗА NGINX НАСТОЯЩИЙ АДРЕС ЛЕЖИТ НЕ В REMOTE_ADDR. Apache видит соединение
 * от локального nginx, и без разбора заголовков ограничение считало бы всех
 * посетителей одним человеком. Заголовку верим только тогда, когда запрос
 * действительно пришёл с петли.
 *
 * Спуфинг заголовка обойдёт этот предел, и это принятая цена: ограничение
 * стоит против тупого потока, а не против прицельной атаки. От прицельной
 * защищают ловушка и часы, которые адрес не читают вовсе.
 */
function clientIp(): string
{
    $remote = (string) ($_SERVER['REMOTE_ADDR'] ?? '');
    $loopback = $remote === '' || $remote === '127.0.0.1' || $remote === '::1';
    if ($loopback) {
        foreach (['HTTP_X_REAL_IP', 'HTTP_X_FORWARDED_FOR'] as $header) {
            $value = (string) ($_SERVER[$header] ?? '');
            if ($value === '') {
                continue;
            }
            $first = trim(explode(',', $value)[0]);
            if (filter_var($first, FILTER_VALIDATE_IP) !== false) {
                return $first;
            }
        }
    }
    return $remote !== '' ? $remote : 'неизвестен';
}

/** Куда складывать отметки. Вне корня сайта: список адресов не для чужих глаз. */
function rateDir(): ?string
{
    $tmp = sys_get_temp_dir();
    if ($tmp === '' || !is_dir($tmp) || !is_writable($tmp)) {
        return null;
    }
    $dir = $tmp . '/elementst-lead';
    if (!is_dir($dir) && !@mkdir($dir, 0700, true) && !is_dir($dir)) {
        return null;
    }
    return is_writable($dir) ? $dir : null;
}

$rateDir = rateDir();
$rateFile = null;
$stamps = [];
if ($rateDir !== null) {
    /* Адрес хешируется: на диске лежат отметки времени, а не список тех, кто
       заходил. Соль — из настроек, отдельного секрета для этого не нужно. */
    $key = hash('sha256', clientIp() . '|' . $config['to'] . '|' . $config['from']);
    $rateFile = $rateDir . '/' . substr($key, 0, 32);
    $now = time();
    if (is_file($rateFile)) {
        $saved = array_map('intval', array_filter(explode(',', (string) @file_get_contents($rateFile))));
        $stamps = array_values(array_filter($saved, static fn(int $t): bool => $now - $t < 86400));
    }
    $lastTen = count(array_filter($stamps, static fn(int $t): bool => $now - $t < 600));
    if ($lastTen >= 3 || count($stamps) >= 12) {
        reply(429, [
            'ok' => false,
            'error' => 'С этого адреса уже отправлено несколько заявок. Позвоните — так быстрее.',
        ]);
    }
}

/* ─── ПОЛЯ ───────────────────────────────────────────────────────────────
 *
 * Всё приходит строками. Управляющие символы вырезаются сразу и у всех
 * полей: в теле письма им делать нечего, а в заголовке перевод строки — это
 * готовая подстановка чужих заголовков.
 */
function field(string $name, int $limit): string
{
    $raw = $_POST[$name] ?? '';
    if (!is_string($raw)) {
        return '';
    }
    $clean = preg_replace('/[\x00-\x1F\x7F]+/u', ' ', $raw) ?? '';
    $clean = trim($clean);
    return mb_substr($clean, 0, $limit, 'UTF-8');
}

/** Сколько цифр в строке. Телефон проверяется по ним, а не по виду. */
function digits(string $s): int
{
    return preg_match_all('/\d/u', $s);
}

$name     = field('name', 80);
$phone    = field('phone', 32);
$company  = field('company', 120);
$material = field('material', 160);
$amount   = field('amount', 40);
$address  = field('address', 200);
$deadline = field('deadline', 80);
$comment  = field('comment', 2000);
$source   = field('source', 60);

/**
 * ПОЗИЦИИ ЗАЯВКИ ИЗ ПАНЕЛИ КАТАЛОГА.
 *
 * Приходят одним полем JSON: название, количество и цена — уже готовыми к
 * чтению строками, собранными на витрине теми же хелперами, что и карточки.
 * Считать их заново на сервере нечем и незачем: прайс лежит в TypeScript, а
 * менеджер всё равно сверяет цену по своему.
 *
 * Разбор недоверчивый: чужой не по формату вход, слишком длинный список и
 * слишком длинные строки просто отбрасываются. В письмо уходит текст, и
 * навредить он не может, но раздуть его на мегабайт — вполне.
 */
$items = [];
$rawItems = $_POST['items'] ?? '';
if (is_string($rawItems) && $rawItems !== '') {
    $parsed = json_decode($rawItems, true);
    if (is_array($parsed)) {
        foreach (array_slice($parsed, 0, 60) as $row) {
            if (!is_array($row)) {
                continue;
            }
            $clean = static function ($value, int $limit): string {
                if (!is_string($value)) {
                    return '';
                }
                $text = preg_replace('/[\x00-\x1F\x7F]+/u', ' ', $value) ?? '';
                return mb_substr(trim($text), 0, $limit, 'UTF-8');
            };
            $title = $clean($row['name'] ?? '', 120);
            if ($title === '') {
                continue;
            }
            $items[] = [
                'name' => $title,
                'qty'  => $clean($row['qty'] ?? '', 40),
                'sum'  => $clean($row['sum'] ?? '', 40),
            ];
        }
    }
}

/* ─── ПРОВЕРКА ПОЛЕЙ НА СЕРВЕРЕ ──────────────────────────────────────────
 *
 * Браузерная проверка — удобство, а не защита: до скрипта можно достучаться
 * curl'ом, минуя форму. Условия здесь ТЕ ЖЕ, что в форме, слово в слово, и
 * тексты ошибок те же — иначе человек увидел бы у одного поля две разные
 * претензии в зависимости от того, где сработала проверка.
 */
$errors = [];

if (mb_strlen($name, 'UTF-8') < 2) {
    $errors['name'] = 'Как к вам обращаться?';
}
if (digits($phone) < 10) {
    $errors['phone'] = 'Нужен номер из 10 цифр — на него перезвоним';
}
if ($amount !== '') {
    /* Пробелы выбрасываются те же три, что и в форме: сайт сам печатает
       объёмы разрядкой, и скопированное из своей же строки поле не должно
       отвергаться. Единица измерения на конце разрешена — форма присылает
       количество вместе с ней. */
    $bare = preg_replace('/[\s\x{00A0}\x{202F}]/u', '', $amount) ?? '';
    $bare = preg_replace('/(м3|м³|т)$/u', '', $bare) ?? '';
    $bare = str_replace(',', '.', $bare);
    if ($bare !== '' && (!is_numeric($bare) || (float) $bare <= 0)) {
        $errors['amount'] = 'Количество числом, например 20 или 12,5';
    }
}
/* Перевод строки в поле, которое уходит в ЗАГОЛОВОК письма, — это готовая
   подстановка чужих заголовков. Управляющие символы вырезает field(), но
   проверка стоит и здесь: она про безопасность, и полагаться на то, что
   выше кто-то не переставит порядок вызовов, нельзя. */
foreach (['name' => $name, 'phone' => $phone] as $key => $value) {
    if (preg_match('/[\r\n]/', $value) === 1) {
        $errors[$key] = 'Недопустимый символ в поле';
    }
}

if ($errors !== []) {
    reply(422, ['ok' => false, 'errors' => $errors]);
}

/* ─── ЛОВУШКИ ───────────────────────────────────────────────────────────
 *
 * ПОРЯДОК ЗДЕСЬ ЗНАЧИМ, И ОН ВЫБРАН ЗАМЕРОМ. Пока ловушки стояли перед
 * разбором полей, ПУСТАЯ форма получала ответ «ок»: у неё нет поля часов,
 * и она проваливалась в ловушку раньше, чем кто-нибудь спрашивал про имя и
 * телефон. Снаружи это выглядело так, будто сервер принял пустую заявку.
 *
 * Теперь сперва разбор полей — мусор и пустота честно получают 422, тот же
 * ответ, что и в форме, — и только заполненное правильно проходит через
 * ловушки. Бот, приславший похожее на заявку, уходит с «ок» и без письма;
 * бот, приславший мусор, узнаёт ровно то же, что видит человек в форме.
 */

/* ─── ЛОВУШКА ────────────────────────────────────────────────────────────
 *
 * Поле «email» в форме есть, но человеку его не видно и табом до него не
 * дойти. Имя выбрано не случайно: у настоящей формы поля почты НЕТ вовсе,
 * а бот заполняет всё, что похоже на адрес, — именно на «email» он и
 * попадается первым делом.
 *
 * Заполнено — отвечаем успехом и не отправляем ничего.
 */
if (trim((string) ($_POST['email'] ?? '')) !== '') {
    reply(200, ['ok' => true]);
}

/* ─── ЧАСЫ ───────────────────────────────────────────────────────────────
 *
 * Форма присылает, сколько миллисекунд прошло с её появления на странице.
 * Меньше двух секунд — это не человек: чтобы отправить, надо набрать имя и
 * десять цифр телефона. Даже автозаполнение браузера требует навести
 * курсор, выбрать запись и нажать кнопку.
 *
 * Поля нет вовсе — тоже бот: значит, форму не открывали, а постучались
 * прямо в скрипт.
 *
 * Верхняя граница отсекает старую вкладку, оставленную открытой на сутки:
 * такие отправки почти всегда чужой скрипт, повторяющий давний запрос.
 */
$elapsed = isset($_POST['elapsed']) ? (int) $_POST['elapsed'] : -1;
if ($elapsed < 2000 || $elapsed > 12 * 60 * 60 * 1000) {
    reply(200, ['ok' => true]);
}

/* ─── ПИСЬМО ─────────────────────────────────────────────────────────────
 *
 * Тело собирается ЗДЕСЬ, из проверенных полей, а не берётся готовым текстом
 * от браузера. Причина простая: то, что пришло от клиента, письмом стать не
 * должно без разбора, а имя и телефон всё равно нужны отдельно — они идут в
 * тему и в заголовки.
 */
$lines = [];
$lines[] = 'Заявка с сайта elementst.ru';
$lines[] = str_repeat('—', 40);
$lines[] = '';
$lines[] = 'Имя:              ' . ($name !== '' ? $name : '—');
$lines[] = 'Телефон:          ' . ($phone !== '' ? $phone : '—');
if ($company !== '') {
    $lines[] = 'Компания:         ' . $company;
}
$lines[] = '';
if ($items !== []) {
    /* Заявка из панели каталога — это список, и строка «Материал» тут была бы
       прочерком на месте главного. Нумерация своя: по ней менеджер и человек
       на телефоне называют одну и ту же позицию. */
    $lines[] = 'Позиции (' . count($items) . '):';
    foreach ($items as $i => $row) {
        $lines[] = sprintf('  %d. %s', $i + 1, $row['name']);
        $tail = trim($row['qty'] . ($row['sum'] !== '' ? '   ' . $row['sum'] : ''));
        if ($tail !== '') {
            $lines[] = '     ' . $tail;
        }
    }
} else {
    $lines[] = 'Материал:         ' . ($material !== '' ? $material : '—');
    $lines[] = 'Количество:       ' . ($amount !== '' ? $amount : '—');
}
$lines[] = '';
$lines[] = 'Адрес объекта:    ' . ($address !== '' ? $address : '—');
$lines[] = 'Срок поставки:    ' . ($deadline !== '' ? $deadline : '—');
if ($comment !== '') {
    $lines[] = '';
    $lines[] = 'Комментарий:';
    $lines[] = $comment;
}
$lines[] = '';
$lines[] = str_repeat('—', 40);
if ($source !== '') {
    $lines[] = 'Откуда:           ' . $source;
}
$lines[] = 'Время:            ' . date('d.m.Y H:i') . ' по серверу';
$body = implode("\r\n", $lines) . "\r\n";

/**
 * Заголовок с кириллицей по RFC 2047.
 *
 * Кодировать надо ОБЯЗАТЕЛЬНО: голый UTF-8 в теме доходит до части почтовых
 * программ кракозябрами, а до части не доходит вовсе. Кодированное слово по
 * стандарту не длиннее 75 знаков, поэтому длинная тема режется на несколько
 * слов — и режется по СИМВОЛАМ, а не по байтам: разрубленная посередине
 * кириллическая буква ломает всю строку.
 */
function mimeHeader(string $text): string
{
    if (preg_match('/^[\x20-\x7E]*$/', $text) === 1) {
        return $text;
    }
    /* 45 байт исходника → 60 знаков base64 → 72 с обёрткой «=?UTF-8?B??=». */
    $limit = 45;
    $parts = [];
    $chunk = '';
    foreach (preg_split('//u', $text, -1, PREG_SPLIT_NO_EMPTY) ?: [] as $ch) {
        if (strlen($chunk) + strlen($ch) > $limit) {
            $parts[] = $chunk;
            $chunk = '';
        }
        $chunk .= $ch;
    }
    if ($chunk !== '') {
        $parts[] = $chunk;
    }
    $encoded = array_map(static fn(string $p): string => '=?UTF-8?B?' . base64_encode($p) . '?=', $parts);
    /* Между кодированными словами — перенос с пробелом: так их склеивает
       получатель, не вставляя лишнего пробела в текст темы. */
    return implode("\r\n ", $encoded);
}

$subjectText = 'Заявка с сайта — ' . ($name !== '' ? $name : 'без имени')
    . ($phone !== '' ? ', ' . $phone : '');
$subject = mimeHeader($subjectText);

$from = (string) $config['from'];
$to   = (string) $config['to'];

$headers = [
    'MIME-Version: 1.0',
    'Content-Type: text/plain; charset=UTF-8',
    /* base64, а не 8bit: часть промежуточных серверов до сих пор не
       восьмибитная, и кириллица в теле у них рассыпается. */
    'Content-Transfer-Encoding: base64',
    /* ОТПРАВИТЕЛЬ — С НАШЕГО ДОМЕНА. Иначе письмо уйдёт в спам или будет
       отвергнуто: почта получателя проверяет, разрешено ли этому серверу
       отправлять от имени домена в поле From. */
    'From: ' . mimeHeader('Заявка с сайта') . ' <' . $from . '>',
    'X-Mailer: elementst.ru',
];

$sent = mail(
    $to,
    $subject,
    rtrim(chunk_split(base64_encode($body), 76, "\r\n")),
    implode("\r\n", $headers),
    /* Конверт тоже подписывается нашим адресом. Без этого sendmail ставит
       отправителем пользователя системы (вроде u3626726@server.hosting), и
       письмо не сходится с доменом в From — верный путь в спам. */
    '-f' . $from
);

if (!$sent) {
    reply(502, [
        'ok' => false,
        'error' => 'Почтовая служба сервера отказала. Позвоните — заявку примем по телефону.',
    ]);
}

/* Отметка ставится ТОЛЬКО после того, как письмо ушло. Отказ почтовой
   подсистемы не должен съедать попытку: человек нажмёт «ещё раз», и предел
   не должен сработать раньше времени. */
if ($rateFile !== null) {
    $stamps[] = time();
    @file_put_contents($rateFile, implode(',', $stamps), LOCK_EX);
}

reply(200, ['ok' => true]);
