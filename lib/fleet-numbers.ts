/**
 * ЦИФРЫ БЛОКА «ПАРК И ОБЪЁМЫ».
 *
 * ⚠️ Заглушки: порядок величин правдоподобный для поставщика такого
 * размера, но настоящих чисел заказчик не давал. Открытый вопрос.
 *
 * Это витринные числа, а не тарифы: парк машин с тарифами и грузоподъёмностью
 * лежит в pricing.ts (FLEET) и к этому списку отношения не имеет. Четыре
 * записи там — ТИПЫ машин, которыми считается доставка; число 24 здесь —
 * физические единицы техники. Разные величины, и путать их нельзя.
 */

export interface FleetNumber {
  /** Число. Разгоняется счётчиком при входе в кадр. */
  value: number;
  /** Единица рядом с числом. Пустая строка — единицы нет. */
  unit: string;
  /** Подпись под числом. */
  label: string;
  /** Уточнение под подписью. */
  note: string;
  /**
   * Главное число блока: оно стоит слева отдельной панелью и крупнее
   * остальных. Признак явный, а не «то, у которого единица м³»: поиск по
   * значению ломался бы от любой правки данных.
   */
  lead?: boolean;
}

export const FLEET_NUMBERS: FleetNumber[] = [
  { value: 24, unit: '', label: 'единицы техники', note: 'самосвалы 10–30 м³, свои и партнёрские' },
  { value: 1800, unit: 'м³', label: 'в сутки', note: 'пиковая отгрузка с трёх площадок', lead: true },
  { value: 150, unit: 'км', label: 'радиус доставки', note: 'от МКАД по всем направлениям' },
  { value: 11, unit: '', label: 'лет на рынке', note: 'с 2015 года, более 900 объектов' },
];

/**
 * Главное число и остальные. Если признака lead нет ни у одной записи,
 * главным становится первая, а пустой список отдаёт null — блок в этом
 * случае просто не рисует панель, а не роняет сборку.
 */
export const FLEET_LEAD: FleetNumber | null =
  FLEET_NUMBERS.find((n) => n.lead) ?? FLEET_NUMBERS[0] ?? null;

export const FLEET_REST: FleetNumber[] = FLEET_NUMBERS.filter((n) => n !== FLEET_LEAD);
