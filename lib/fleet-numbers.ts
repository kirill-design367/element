/**
 * ЦИФРЫ БЛОКА «ПАРК И ОБЪЁМЫ».
 *
 * ⚠️ Заглушки: порядок величин правдоподобный для поставщика такого
 * размера, но настоящих чисел заказчик не давал. Открытый вопрос.
 *
 * Это витринные числа, а не данные расчёта: парк машин с объёмами и
 * грузоподъёмностью лежит в pricing.ts (FLEET) и к этому списку отношения не
 * имеет. Четыре записи там — ТИПЫ машин, по которым подбираются рейсы; число
 * 24 здесь — физические единицы техники. Разные величины, и путать их нельзя.
 *
 * Числа «150 км радиус доставки» здесь больше нет: доставки у нас нет вовсе.
 * На его месте — сколько позиций в каталоге, и это считается из данных.
 */

import { FLEET_VOLUME_RANGE } from './pricing';
import { CATEGORIES, POSITIONS_TOTAL } from './catalog';
import { OBJECTS_DONE, SINCE_YEAR } from './company';

export interface FleetNumber {
  /** Число. Разгоняется счётчиком при входе в кадр. */
  value: number;
  /** Единица рядом с числом. Пустая строка — единицы нет. */
  unit: string;
  /** Подпись под числом. */
  label: string;
  /** Уточнение под подписью. */
  note: string;
  /**
   * Главное число блока: оно стоит слева отдельной панелью и крупнее
   * остальных. Признак явный, а не «то, у которого единица м³»: поиск по
   * значению ломался бы от любой правки данных.
   */
  lead?: boolean;
}

/**
 * Числа, которые уже где-то есть, сюда не переписываются.
 *
 * Разброс объёмов самосвалов считается из парка в pricing.ts, радиус
 * позиции и группы — из каталога, годы на рынке — из года основания. Раньше
 * все они стояли здесь строками: «самосвалы 10–30 м³», «150 км», «с 2015
 * года» рядом с отдельным числом 11. Правка парка оставляла витрину врать.
 *
 * Число 24 своё: это физические единицы техники, а в FLEET четыре ТИПА
 * машин, которыми считается доставка. Разные величины, вывести одну из
 * другой нельзя.
 */
export const FLEET_NUMBERS: FleetNumber[] = [
  {
    value: 24,
    unit: '',
    label: 'единицы техники',
    note: `самосвалы ${FLEET_VOLUME_RANGE[0]}–${FLEET_VOLUME_RANGE[1]} м³, свои и партнёрские`,
  },
  { value: 1800, unit: 'м³', label: 'в сутки', note: 'пиковая отгрузка с трёх площадок', lead: true },
  {
    value: POSITIONS_TOTAL,
    unit: '',
    label: 'позиций в каталоге',
    note: `${CATEGORIES.length} групп: инертные и металлопрокат`,
  },
  {
    value: new Date().getFullYear() - SINCE_YEAR,
    unit: '',
    label: 'лет на рынке',
    note: `с ${SINCE_YEAR} года, более ${OBJECTS_DONE} объектов`,
  },
];

/**
 * Главное число и остальные. Если признака lead нет ни у одной записи,
 * главным становится первая, а пустой список отдаёт null — блок в этом
 * случае просто не рисует панель, а не роняет сборку.
 */
export const FLEET_LEAD: FleetNumber | null =
  FLEET_NUMBERS.find((n) => n.lead) ?? FLEET_NUMBERS[0] ?? null;

export const FLEET_REST: FleetNumber[] = FLEET_NUMBERS.filter((n) => n !== FLEET_LEAD);
