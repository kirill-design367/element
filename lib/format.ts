/** Форматирование чисел. Везде неразрывные пробелы, чтобы «₽» не отрывался. */

const NBSP = ' ';

/**
 * Все пробелы в строке — неразрывными.
 *
 * Нужно не для переносов, а из-за шрифта: в CoFo Sans фича tnum подменяет
 * обычный пробел широким табличным — 13 px против 4 при кегле 20, — и в
 * элементе с классом .tnum фраза расходится разрядкой. Неразрывный пробел
 * фича не трогает. Поэтому всё, что стоит внутри табличных цифр и содержит
 * не только цифры — телефон, счётчик найденного, единицы, — проходит через
 * этот хелпер.
 */
export function nbsp(s: string): string {
  return s.replace(/ /g, NBSP);
}

export function rub(n: number): string {
  return `${new Intl.NumberFormat('ru-RU').format(Math.round(n)).replace(/\s/g, NBSP)}${NBSP}₽`;
}

/**
 * Цена, которой нет в прайсе заказчика.
 *
 * Одна формулировка на весь сайт: карточка каталога, лента материалов, панель
 * цен первого экрана, калькулятор, панель заявки, письмо. Ноль на месте
 * отсутствующей цены — неправда, прочерк читается как «поле не заполнили», а
 * «ориентировочно» с числом из ниоткуда — как прайс.
 */
export const ON_REQUEST = 'уточняйте у менеджера';

/** Цена или честное «по запросу». */
export function rubOr(n: number | null): string {
  return n === null ? ON_REQUEST : rub(n);
}

export function num(n: number, digits = 0): string {
  return new Intl.NumberFormat('ru-RU', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  })
    .format(n)
    .replace(/\s/g, NBSP);
}

/** Кубы показываем без хвоста, когда он нулевой: 12 м³, но 12,5 м³. */
export function volume(n: number): string {
  const r = Math.round(n * 10) / 10;
  return `${num(r, Number.isInteger(r) ? 0 : 1)}${NBSP}м³`;
}

export function tons(n: number): string {
  const r = Math.round(n * 10) / 10;
  return `${num(r, Number.isInteger(r) ? 0 : 1)}${NBSP}т`;
}

/** «1 рейс», «2 рейса», «5 рейсов». */
export function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return few;
  return many;
}

export function rides(n: number): string {
  return `${num(n)}${NBSP}${plural(n, 'рейс', 'рейса', 'рейсов')}`;
}

/**
 * Типографские неразрывные пробелы. Текст не меняется — меняются только
 * места, где строке разрешено рваться:
 *   • короткое слово (предлог, союз, частица) не остаётся в конце строки;
 *   • число не отрывается от единицы измерения: «150 км», «20 м³»;
 *   • последнее слово не остаётся одно на новой строке.
 * Последнее и есть висячая строка, из-за которой «МКАД» уезжал один, а
 * «доставкой» стояло второй строкой заголовка.
 */
export function typo(s: string): string {
  return s
    .replace(/(^|[\s(«"])([а-яёa-z]{1,2})\s+/gi, '$1$2\u00A0')
    /* Граница \b здесь не работала: в JavaScript «словом» для неё считается
       только [A-Za-z0-9_], кириллица — нет. После «м³» или «кг» границы не
       возникало, правило не срабатывало ни разу, и число от единицы
       отрывалось везде, кроме случая, когда единица — последнее слово
       (это ловит третье правило). Вместо \b — проверка, что дальше не
       продолжается слово. */
    .replace(/(\d)\s+([а-яё]{1,3}[²³]?)(?![а-яёa-z])/gi, '$1\u00A0$2')
    .replace(/\s+(\S+)$/, '\u00A0$1');
}


/**
 * МАСКА РОССИЙСКОГО НОМЕРА: +7 (999) 123-45-67.
 *
 * Плейсхолдер обещал маску, а поле принимало что угодно — валидация только
 * считала цифры. Теперь ввод форматируется на лету и, что важнее, корректно
 * переживает вставку из буфера: «89991234567», «8 999 123-45-67»,
 * «+7(999)1234567» и «7 999 123 45 67» приводятся к одному виду.
 *
 * Разбор идёт по цифрам, а не по символам: у 8 и 7 в начале одно и то же
 * значение — код страны, — и обе отбрасываются в пользу +7. Номер без кода
 * («9991234567») тоже понимается: десять цифр это уже полный номер.
 */
export function phoneMask(raw: string): string {
  let d = raw.replace(/\D/g, '');
  if (d.startsWith('8')) d = '7' + d.slice(1);
  if (d.startsWith('7')) d = d.slice(1);
  d = d.slice(0, 10);
  /* Пустой результат при непустом вводе бывает в одном случае: набрана
     ровно одна цифра кода страны, 7 или 8. Показываем начало маски, иначе
     первая набранная цифра пропадала бы на глазах. */
  if (!d) return /[\d+]/.test(raw) ? '+7 (' : '';
  let out = '+7 (' + d.slice(0, 3);
  if (d.length >= 3) out += ') ' + d.slice(3, 6);
  if (d.length >= 6) out += '-' + d.slice(6, 8);
  if (d.length >= 8) out += '-' + d.slice(8, 10);
  return out;
}

/** Сколько значащих цифр набрано в номере — без кода страны. */
export function phoneDigits(raw: string): number {
  let d = raw.replace(/\D/g, '');
  if (d.startsWith('8')) d = '7' + d.slice(1);
  if (d.startsWith('7')) d = d.slice(1);
  return Math.min(d.length, 10);
}
