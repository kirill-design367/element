/** Ключ слота по идентификатору категории: shcheben → categoryShcheben. */
export function categorySlot(id: string): string {
  return `category${id.charAt(0).toUpperCase()}${id.slice(1)}`;
}

/** Путь к статике с учётом basePath GitHub Pages. */
export function asset(path: string): string {
  const base = process.env.NEXT_PUBLIC_BASE_PATH ?? '';
  return `${base}${path}`;
}

/**
 * srcset для одного формата. Ширины реальные, поэтому браузер выбирает файл
 * сам по ширине показа и плотности экрана — телефон не тянет десктопный кадр.
 */
export function srcSet(f: PhotoFile, ext: 'webp' | 'jpg'): string {
  return f.widths.map((w) => `${asset(`/img/${f.name}-${w}.${ext}`)} ${w}w`).join(', ');
}

/** Запасной адрес для браузера без srcset: средняя ширина, обычный JPEG. */
export function fallbackSrc(f: PhotoFile): string {
  const w = f.widths[Math.min(1, f.widths.length - 1)];
  return asset(`/img/${f.name}-${w}.jpg`);
}

/**
 * Миниатюра 24 px шириной в виде data-URI — та самая размытая подложка,
 * которая стоит на месте кадра, пока он грузится. Несколько сотен байт,
 * лежит прямо в разметке: отдельный запрос за заглушкой стоил бы дороже
 * самой заглушки.
 */
export function lqipOf(f: PhotoFile): string {
  return (LQIP as Record<string, string>)[f.name] ?? '';
}
