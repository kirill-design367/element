/** Ключ слота по идентификатору категории: shcheben → categoryShcheben. */
export function categorySlot(id: string): string {
  return `category${id.charAt(0).toUpperCase()}${id.slice(1)}`;
}

/** Путь к статике с учётом basePath GitHub Pages. */
export function asset(path: string): string {
  const base = process.env.NEXT_PUBLIC_BASE_PATH ?? '';
  return `${base}${path}`;
}
